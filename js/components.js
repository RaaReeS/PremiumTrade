  // ─── Modal ───
  showModal({ title, content, onClose, footer } = {}) {
    const existing = document.querySelector('.modal-overlay');
    if (existing) existing.remove();

    const overlay = document.createElement('div');
    overlay.className = 'modal-overlay';
    overlay.innerHTML = `
      <div class="modal">
        <div class="modal-header">
          <h3>${title || ''}</h3>
          <button class="modal-close" data-action="close">
            <svg xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><line x1="18" y1="6" x2="6" y2="18"/><line x1="6" y1="6" x2="18" y2="18"/></svg>
          </button>
        </div>
        <div class="modal-body">${content || ''}</div>
        ${footer ? `<div class="modal-footer">${footer}</div>` : ''}
      </div>
    `;

    document.body.appendChild(overlay);
    document.body.style.overflow = 'hidden';

    overlay.addEventListener('click', (e) => {
      if (e.target === overlay) {
        overlay.remove();
        document.body.style.overflow = '';
        if (onClose) onClose();
      }
    });

    overlay.querySelector('[data-action="close"]')?.addEventListener('click', () => {
      overlay.remove();
      document.body.style.overflow = '';
      if (onClose) onClose();
    });

    return overlay;
  },

  // ─── Confirm Dialog ───
  confirm({ title, message, confirmText = 'Confirmar', cancelText = 'Cancelar', variant = 'danger', onConfirm, onCancel } = {}) {
    const overlay = this.showModal({
      title: title || 'Confirmar',
      content: `
        <div class="text-center">
          <p style="color: var(--text-secondary); font-size: 14px; margin-bottom: 8px;">${message || ''}</p>
          <p style="color: var(--text-muted); font-size: 13px;">Esta acción no se puede deshacer.</p>
        </div>
      `,
      footer: `
        <button class="btn btn-secondary" data-action="cancel">${cancelText}</button>
        <button class="btn btn-${variant}" data-action="confirm">${confirmText}</button>
      `,
      onClose: () => { if (onCancel) onCancel(); },
    });

    overlay.querySelector('[data-action="cancel"]').addEventListener('click', () => {
      overlay.remove();
      if (onCancel) onCancel();
    });

    overlay.querySelector('[data-action="confirm"]').addEventListener('click', () => {
      overlay.remove();
      if (onConfirm) onConfirm();
    });

    return overlay;
  },

  // ─── Format currency ───
  formatCurrency(value) {
    if (value === null || value === undefined) return '—';
    return value.toLocaleString('es-ES', { style: 'currency', currency: 'EUR' });
  },

  // ─── Format date ───
  _parseDate(dateStr) {
    if (!dateStr) return null;
    // Si ya es datetime ISO (tiene T), usarlo directo
    if (dateStr.includes('T')) return new Date(dateStr);
    // Si es solo fecha (YYYY-MM-DD), agregar mediodía para evitar timezone shifts
    return new Date(dateStr + 'T12:00:00');
  },

  formatDate(dateStr) {
    const d = this._parseDate(dateStr);
    if (!d || isNaN(d)) return '—';
    return d.toLocaleDateString('es-ES', { year: 'numeric', month: 'long', day: 'numeric' });
  },

  formatDateShort(dateStr) {
    const d = this._parseDate(dateStr);
    if (!d || isNaN(d)) return '—';
    return d.toLocaleDateString('es-ES', { year: 'numeric', month: 'short', day: 'numeric' });
  },

